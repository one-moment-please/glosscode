// Runs the mockup's own JavaScript (docs/mockup/index.html) on every sample program in examples/ and
// every edge case in tests/cases/, and
// writes what it shows to tests/golden/*.json: the English word, unit and description for every word,
// and every problem the checks report. The C core's tests (tests/test_golden.c) compare against these,
// so the core and the mockup stay in step. Run from the repo root after changing either:
//   node scripts/make-core-goldens.mjs           write the files
//   node scripts/make-core-goldens.mjs --check   fail if any file would change (used by CI)
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import vm from "node:vm";

const check = process.argv.includes("--check");
const html = readFileSync("docs/mockup/index.html", "utf8");
const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m => m[1]);

// A stand-in for the browser: every DOM call returns another stand-in, so the page's start-up code
// runs without drawing anything. Only the pure functions are used afterwards.
const stub = new Proxy(function(){}, {
  get(t, k){ if (k===Symbol.iterator) return function*(){}; if (k===Symbol.toPrimitive) return () => 0; if (k==="length") return 0; if (k==="then") return undefined; return stub; },
  set(){ return true; }, apply(){ return stub; }, construct(){ return stub; }, has(){ return true; }
});
const ctx = { console, document:stub, navigator:stub, localStorage:stub, location:{ search:"", href:"" }, fetch:async () => ({ ok:false }),
  setTimeout:() => 0, setInterval:() => 0, clearInterval(){}, clearTimeout(){}, requestAnimationFrame(){}, getComputedStyle:() => stub,
  matchMedia:() => stub, addEventListener(){}, URLSearchParams, Math, JSON };
ctx.window = ctx; vm.createContext(ctx);
vm.runInContext(scripts.join("\n;\n").replace(/^(const|let) /gm, "var ") + `
;globalThis.__api = { set doc(v){ doc = v; }, get view(){ return view; }, translateAll, checkProgram, splitBlocks, tokenize,
  use(id, s){ machineId = id; style = s; setDialect(); }, MACHINES };`, ctx);
const A = ctx.__api;

const MILLS = ["haas_vf2", "fanuc_0imf", "fanuc_0mc", "okuma_m560"], LATHES = ["haas_st10", "okuma_lb3000"];
const LATHE_FILES = ["LATHE_CHECKS.nc", "SHAFT_OD.nc", "LATHE_EDGE.nc"];
const OKUMA_FILES = ["OKUMA_PLATE.MIN", "OKUMA_CALLS.MIN"];
let changed = 0;
const write = (file, out) => {
  if (existsSync(file) && readFileSync(file, "utf8")===out) return;
  changed++;
  if (check) console.error("Out of date:", file); else { writeFileSync(file, out); console.log("Wrote", file); }
};
const goldens = [];
const sources = ["examples", "tests/cases"].flatMap(dir => readdirSync(dir).sort().map(name => ({ dir, name })));
for (const { dir, name } of sources){
  const text = readFileSync(dir + "/" + name, "latin1");
  const lines = text.split(/\r\n|\n|\r/); if (lines.length > 1 && lines[lines.length-1]==="") lines.pop();
  const doc = []; for (const line of lines) A.splitBlocks(line).blocks.forEach(b => doc.push(A.tokenize(b)));
  const machines = LATHE_FILES.includes(name) ? LATHES : OKUMA_FILES.includes(name) ? ["okuma_m560", ...MILLS.filter(m => m!=="okuma_m560")] : MILLS;
  const runs = [];
  for (const id of machines) for (const s of id===machines[0] ? ["long", "short"] : ["long"]){
    A.use(id, s); A.doc = doc.map(t => [...t]); A.translateAll();
    const words = A.view.map(cells => cells.map(c => {
      const o = { g:c.g, e:c.e }; if (c.u) o.u = c.u; o.d = c.d2 || c.d || ""; if (c.unk) o.unk = true; if (c.imp) o.imp = true; if (c.cm) o.cm = true; return o; }));
    const problems = A.checkProgram().map(p => ({ li:p.li, id:p.id, sev:p.sev, msg:p.msg }));
    runs.push({ machine:id, style:s, words, problems });
  }
  const out = JSON.stringify({ file:name, about:"Generated by scripts/make-core-goldens.mjs from the mockup. Don't edit by hand.", lines:doc, runs }, null, 1) + "\n";
  const file = `tests/golden/${name.replace(/\./g, "_")}.json`;
  goldens.push({ example:dir + "/" + name, golden:file });
  write(file, out);
}
// The machine profiles the mockup ships with, and the list of files above, for the C tests.
write("tests/golden/index.json", JSON.stringify({ about:"Generated by scripts/make-core-goldens.mjs. Don't edit by hand.",
  machines:A.MACHINES, library:[...readdirSync("data/library").filter(f => f.endsWith(".json")).sort().map(f => ({ file:"data/library/" + f, source:"builtin" })),
    ...readdirSync("docs/subprogram-library/examples").filter(f => f.endsWith(".json")).sort().map(f => ({ file:"docs/subprogram-library/examples/" + f, source:"shop" }))],
  goldens }, null, 1) + "\n");
if (check && changed){ console.error("Run: node scripts/make-core-goldens.mjs"); process.exit(1); }
if (!changed) console.log("Goldens up to date");
